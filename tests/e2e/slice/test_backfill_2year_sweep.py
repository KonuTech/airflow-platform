def test_idempotent_rerun_produces_zero_additional_rows(
    sweep_corpus: _Corpus,  # noqa: ARG001 -- ensures the corpus fixture (and its upload) stays alive
    sweep_state: _SweepState,
    kubectl: Callable[..., subprocess.CompletedProcess[str]],
    analytics_connection: psycopg.Connection[Any],
    airflow_metadata_connection: psycopg.Connection[Any],
) -> None:
    """QUAL-11: re-invoking the IDENTICAL backfill window produces zero additional rows.

    Pitfall 3: a re-triggered DagRun finding zero new work IS success, not failure --
    `discover_files`' own idempotency-key check means almost every re-triggered tick simply
    no-ops. This test's own row-count/watermark before/after comparison is designed around that
    expected outcome, not around "N discover units returned".
    """
    assert sweep_state.full_sweep_from is not None
    assert sweep_state.full_sweep_to is not None, (
        "sweep_state.full_sweep_to is unset -- test_full_2year_sweep_customers_and_orders must "
        "run first in this module (pytest's default in-file collection order)"
    )

    before_customers_count = _table_row_count(analytics_connection, "normalized.customers")
    before_orders_count = _table_row_count(analytics_connection, "normalized.orders")
    before_customers_watermark = _watermark_cursor_value(
        analytics_connection, dataset=_CUSTOMERS_DATASET
    )
    before_orders_watermark = _watermark_cursor_value(analytics_connection, dataset=_ORDERS_DATASET)

    since_customers_backfill_id = _latest_backfill_id(
        airflow_metadata_connection, dag_id=_CUSTOMERS_DAG_ID
    )
    since_orders_dag_run_pk = _latest_dag_run_pk(airflow_metadata_connection, dag_id=_ORDERS_DAG_ID)

    _invoke_backfill_create(
        kubectl,
        dag_id=_CUSTOMERS_DAG_ID,
        from_iso=sweep_state.full_sweep_from.isoformat(),
        to_iso=sweep_state.full_sweep_to.isoformat(),
        max_active_runs=sweep_state.max_active_runs,
    )
    _wait_for_new_backfill_completed(
        airflow_metadata_connection,
        dag_id=_CUSTOMERS_DAG_ID,
        since_backfill_id=since_customers_backfill_id,
        timeout=900,
    )
    # customers' `publish` task fires its `customers_asset` outlet on every SUCCEEDED run --
    # including a pure no-op re-run (finalize_publication handles an empty staged set the same
    # way) -- so orders' own Asset-triggered cascade re-fires too; wait for ITS re-execution to
    # settle before comparing final counts, rather than a blind sleep.
    _wait_for_new_dag_run_terminal(
        airflow_metadata_connection,
        dag_id=_ORDERS_DAG_ID,
        since_pk=since_orders_dag_run_pk,
        timeout=600,
    )

    after_customers_count = _table_row_count(analytics_connection, "normalized.customers")
    after_orders_count = _table_row_count(analytics_connection, "normalized.orders")
    after_customers_watermark = _watermark_cursor_value(
        analytics_connection, dataset=_CUSTOMERS_DATASET
    )
    after_orders_watermark = _watermark_cursor_value(analytics_connection, dataset=_ORDERS_DATASET)

    assert after_customers_count == before_customers_count, (
        f"expected normalized.customers row count unchanged by the identical re-run, "
        f"before={before_customers_count} after={after_customers_count}"
    )
    assert after_orders_count == before_orders_count, (
        f"expected normalized.orders row count unchanged by the identical re-run, "
        f"before={before_orders_count} after={after_orders_count}"
    )
    assert after_customers_watermark == before_customers_watermark, (
        f"expected meta.watermarks.cursor_value for customers unchanged by the identical "
        f"re-run (INCR-02's '>=, never >' rule holding), before={before_customers_watermark!r} "
        f"after={after_customers_watermark!r}"
    )
    assert after_orders_watermark == before_orders_watermark, (
        f"expected meta.watermarks.cursor_value for orders unchanged by the identical re-run, "
        f"before={before_orders_watermark!r} after={after_orders_watermark!r}"
    )


def test_live_run_concurrent_with_backfill_same_dataset(
    sweep_corpus: _Corpus,  # noqa: ARG001 -- ensures the corpus fixture stays alive
    sweep_state: _SweepState,
    kubectl: Callable[..., subprocess.CompletedProcess[str]],
    analytics_connection: psycopg.Connection[Any],
    airflow_metadata_connection: psycopg.Connection[Any],
) -> None:
    """D-12/D-13: a live customers DagRun runs CONCURRENTLY with an active backfill, no corruption.

    `csv_ingest_customers` stays unpaused for this whole module (session-scoped, autouse
    `_unpause_slice_dags` fixture, `tests/e2e/slice/conftest.py`) and every uploaded file
    permanently matches its `wait_for_files` sensor, so the DAG's own `*/1 * * * *` live schedule
    keeps producing ordinary `backfill_id IS NULL` DagRuns throughout this whole module's
    execution -- this test triggers a FRESH backfill window and polls for a live DagRun to be
    'running' at the SAME sampled instant, rather than assuming architecture guarantees it.
    """
    from_dt, to_dt = _window(offset_minutes=300, span_minutes=2)
    since_id = _latest_backfill_id(airflow_metadata_connection, dag_id=_CUSTOMERS_DAG_ID)
    _invoke_backfill_create(
        kubectl,
        dag_id=_CUSTOMERS_DAG_ID,
        from_iso=from_dt.isoformat(),
        to_iso=to_dt.isoformat(),
        max_active_runs=sweep_state.max_active_runs,
    )

    observed_concurrent = False
    poll_deadline = time.monotonic() + 300
    while time.monotonic() < poll_deadline:
        with airflow_metadata_connection.cursor() as cur:
            cur.execute(
                """
                SELECT (backfill_id IS NULL) AS is_live, count(*)
                  FROM dag_run
                 WHERE dag_id = %s AND state = 'running'
                 GROUP BY backfill_id IS NULL
                """,
                (_CUSTOMERS_DAG_ID,),
            )
            counts = dict(cur.fetchall())
        if counts.get(True, 0) > 0 and counts.get(False, 0) > 0:
            observed_concurrent = True
            break
        time.sleep(_POLL_INTERVAL_SECONDS)

    _wait_for_new_backfill_completed(
        airflow_metadata_connection,
        dag_id=_CUSTOMERS_DAG_ID,
        since_backfill_id=since_id,
        timeout=600,
    )

    assert observed_concurrent, (
        "never observed a customers DagRun with backfill_id IS NOT NULL and a customers DagRun "
        "with backfill_id IS NULL BOTH state='running' at the same sampled instant within 300s "
        "-- D-13's live+backfill concurrency proof requires this overlap to actually occur, not "
        "just be architecturally possible"
    )

    # No corruption: normalized.customers has no duplicate customer_id -- the UNIQUE constraint
    # (migration 0006) would already prevent this at the DB level; this assertion proves the
    # concurrent writes actually serialized cleanly through pg_advisory_xact_lock in practice,
    # not merely that the constraint would have caught a violation had one occurred.
    with analytics_connection.cursor() as cur:
        cur.execute(
            """
            SELECT customer_id, count(*)
              FROM normalized.customers
             GROUP BY customer_id
            HAVING count(*) > 1
             LIMIT 5
            """
        )
        duplicates = cur.fetchall()
    assert not duplicates, (
        f"found duplicate customer_id rows in normalized.customers: {duplicates!r}"
    )
