    assert after_snapshot == before_snapshot, (
        f"expected gold state (event_ts, version_count) for every removed member to be "
        f"BYTE-FOR-BYTE unchanged by the FAILED run -- proving MassDeleteCircuitBreaker is a "
        f"PRE-mutation barrier stage, not a partial-apply-then-fail race. "
        f"before={before_snapshot!r} after={after_snapshot!r}"
    )
