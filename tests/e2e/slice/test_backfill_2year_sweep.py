def _wait_for_dataset_files_terminal(
    conn: psycopg.Connection[Any],
    *,
    dataset: str,
    filenames: Sequence[str],
    timeout: float,
) -> dict[str, dict[str, Any]]:
    """Poll until every `filenames` entry has a `meta.ingestion_runs` row in a terminal status.

    Returns `{filename: {"status": ..., "run_id": ..., "schema_version_id": ..., "file_id": ...}}`.
    A single deadline loop over ALL filenames at once (not N separate per-file polls), matching
    this module's own scale (a handful of files, one discover call drains all of them together).

    `DISTINCT ON (f.filename) ... ORDER BY f.filename, ir.run_id DESC NULLS LAST` -- a file CAN
    have more than one `meta.ingestion_runs` row (a prior attempt that never reached a terminal
    status, e.g. an infra-outage-interrupted run left permanently `RUNNING` with no
    `finished_at`), and a plain `LEFT JOIN` with no ordering returns ALL of them, non-
    deterministically overwriting this function's per-filename dict in whatever order Postgres
    happens to return rows -- which could mean this loop keeps observing a stale, permanently-
    `RUNNING` OLD row forever even after a genuinely NEWER attempt reaches `SUCCEEDED` (live-
    discovered this session: see module docstring). Selecting the highest `run_id` per filename
    is the fix -- the latest attempt is always the one that matters.
    """
    deadline = time.monotonic() + timeout
    results: dict[str, dict[str, Any]] = {}
    while time.monotonic() < deadline:
        with conn.cursor() as cur:
            cur.execute(
                """
                SELECT DISTINCT ON (f.filename)
                       f.filename, f.file_id, ir.status, ir.run_id, ir.schema_version_id
                  FROM meta.files f
                  JOIN meta.datasets d ON d.dataset_id = f.dataset_id
                  LEFT JOIN meta.ingestion_runs ir ON ir.file_id = f.file_id
                 WHERE d.dataset_name = %s AND f.filename = ANY(%s)
                 ORDER BY f.filename, ir.run_id DESC NULLS LAST
                """,
                (dataset, list(filenames)),
            )
            rows = cur.fetchall()
        for filename, file_id, status, run_id, schema_version_id in rows:
            results[filename] = {
                "file_id": file_id,
                "status": status,
                "run_id": run_id,
                "schema_version_id": schema_version_id,
            }
        if len(results) == len(filenames) and all(
            r["status"] in _TERMINAL_RUN_STATUSES for r in results.values()
        ):
            return results
        time.sleep(_POLL_INTERVAL_SECONDS)
    missing = sorted(set(filenames) - results.keys())
    pending = {
        k: v["status"] for k, v in results.items() if v["status"] not in _TERMINAL_RUN_STATUSES
    }
    msg = (
        f"dataset={dataset!r}: not all of {len(filenames)} filenames reached a terminal "
        f"meta.ingestion_runs status within {timeout}s -- missing entirely: {missing}, "
        f"still non-terminal: {pending}"
    )
    raise AssertionError(msg)


def _customer_rows_in_file(
    files: dict[str, bytes], filename: str, customer_id: int
) -> list[dict[str, str]]:
    """Every row in `files[filename]` for `customer_id`, in file order, as `{column: value}` dicts.

    A roster member can legitimately appear MORE than once in one file -- D-11's late-correction
    mechanic (`tools/corpus/dated_series.py`) appends an EXTRA row after the full roster resend,
    so this returns every match, in the SAME order they appear in the file; a caller needing a
    specific occurrence (e.g. the LAST one, the appended correction) indexes into the result
    itself. `sweep_corpus.customers_files` (module-scoped, generated once) is this corpus' own
    single source of truth for exactly what was injected -- reading it directly here means this
    module's own SCD assertions never need to re-derive an expected value via
    `tools.corpus.dated_series`'s private helper functions.
    """
    text = files[filename].decode("utf-8")
    lines = [line for line in text.split("\r\n") if line]
    header = lines[0].split(",")
    matches: list[dict[str, str]] = []
    for line in lines[1:]:
        fields = line.split(",")
        if fields[0] == str(customer_id):
            matches.append(dict(zip(header, fields, strict=True)))
    return matches


def _customer_version_counts(conn: psycopg.Connection[Any]) -> dict[int, int]:
    """`{customer_id: SCD2 version row count}` for every customer_id in `normalized.customers`.

    D-12 (plan 10-07 Task 2)'s own oracle: a full second backfill re-run over the identical
    window must produce a BYTE-FOR-BYTE identical snapshot of this mapping -- not merely an
    unchanged TOTAL row count (which cannot distinguish "zero net change" from "one customer_id
    lost a version while another gained one").
    """
    with conn.cursor() as cur:
        cur.execute("SELECT customer_id, count(*) FROM normalized.customers GROUP BY customer_id")
        rows = cur.fetchall()
    return {int(customer_id): int(count) for customer_id, count in rows}


def _customer_current_state_snapshot(
    conn: psycopg.Connection[Any], customer_ids: Sequence[int]
) -> dict[int, tuple[Any, int]]:
    """`{customer_id: (current version's own event_ts, TOTAL version-row count for that key)}`.

    D-06 (plan 10-07 Task 3)'s own pre/post gold-state oracle: a FAILED run (the mass-delete
    circuit breaker tripping) must leave every one of these values byte-for-byte unchanged --
    proving the breaker is a PRE-mutation barrier stage (D-06's own `BarrierStage` design), not
    a partial-apply-then-fail race. Scoped to `customer_ids` only -- this is a shared,
    cluster-wide table other live e2e suites also write to.
    """
    with conn.cursor() as cur:
        cur.execute(
            """
            SELECT customer_id, event_ts, count(*) OVER (PARTITION BY customer_id)
              FROM normalized.customers
             WHERE customer_id = ANY(%s) AND is_current
            """,
            (list(customer_ids),),
        )
        rows = cur.fetchall()
    return {
        int(customer_id): (event_ts, int(version_count))
        for customer_id, event_ts, version_count in rows
    }


