def _dry_run_tick_count(
    kubectl_fn: Callable[..., subprocess.CompletedProcess[str]],
    *,
    dag_id: str,
    from_iso: str,
    to_iso: str,
) -> int:
    """Invoke `airflow backfill create --dry-run` and count the enumerated ticks.

    Pitfall 1's exact failure mode this guards against: an unbounded window enumerating tens or
    hundreds of thousands of DagRuns. Asserts CLI success separately from the tick count so a
    genuine CLI failure (e.g. `DagNonPeriodicScheduleException`) is never miscounted as `0` ticks.
    """
