def _wait_for_new_dag_run_terminal(
    conn: psycopg.Connection[Any],
    *,
    dag_id: str,
    since_pk: int | None,
    timeout: float,
) -> None:
    """Poll for a `dag_run` row newer than `since_pk` (this dag_id's own `id` PK) to go terminal.

    Used to wait for an Asset-cascade-triggered `csv_ingest_orders` run to settle after a
    customers publish, WITHOUT a blind `sleep(N)` (this codebase's own established
    "sleep-in-e2e-tests is a permanent-flakiness trap" discipline).
    """
    deadline = time.monotonic() + timeout
    last_state: str | None = None
    while time.monotonic() < deadline:
        with conn.cursor() as cur:
            cur.execute(
                "SELECT id, state FROM dag_run WHERE dag_id = %s ORDER BY id DESC LIMIT 1",
                (dag_id,),
            )
            row = cur.fetchone()
        if row is not None:
            pk, state = row
            last_state = state
            if (since_pk is None or pk > since_pk) and state in ("success", "failed"):
                return
        time.sleep(_POLL_INTERVAL_SECONDS)
    msg = (
        f"no NEW dag_run for dag_id={dag_id!r} (since_pk={since_pk!r}) reached a terminal state "
        f"within {timeout}s (last observed state: {last_state!r})"
    )
    raise AssertionError(msg)


