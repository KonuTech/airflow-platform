def test_live_run_concurrent_with_backfill_same_dataset(
    sweep_corpus: _Corpus,  # noqa: ARG001 -- ensures the corpus fixture stays alive
    sweep_state: _SweepState,
    kubectl: Callable[..., subprocess.CompletedProcess[str]],
    analytics_connection: psycopg.Connection[Any],
    airflow_metadata_connection: psycopg.Connection[Any],
) -> None:
    """D-12/D-13: a live customers DagRun runs CONCURRENTLY with an active backfill, no corruption.

    `csv_ingest_customers` stays unpaused for this whole module now (see the removed
    DAG-pause-scoping comment block above `_latest_backfill_id`), so every uploaded file
    permanently matches its `wait_for_files` sensor and the DAG's own `*/1 * * * *` live schedule
    produces ordinary `backfill_id IS NULL` DagRuns throughout this one test's execution -- this
    test triggers a FRESH backfill window and polls for a live DagRun to be 'running' at the SAME
    sampled instant, rather than assuming architecture guarantees it.
    """
    from_dt, to_dt = _window(offset_minutes=300, span_minutes=2)
    since_id = _latest_backfill_id(airflow_metadata_connection, dag_id=_CUSTOMERS_DAG_ID)
    _invoke_backfill_create(
        kubectl,
        dag_id=_CUSTOMERS_DAG_ID,
        from_iso=from_dt.isoformat(),
        to_iso=to_dt.isoformat(),
        max_active_runs=sweep_state.max_active_runs,
    )

    observed_concurrent = False
    # 600s (10 min): customers' live `*/1 * * * *` schedule normally creates a new DagRun within
    # a minute, but under this cluster's real CPU contention (observed live this session) task
    # pod scheduling can queue for several minutes before a task instance actually starts
    # running -- generous headroom over the architecturally-expected ~1 min.
    poll_deadline = time.monotonic() + 600
    while time.monotonic() < poll_deadline:
        with airflow_metadata_connection.cursor() as cur:
            cur.execute(
                """
                SELECT (backfill_id IS NULL) AS is_live, count(*)
                  FROM dag_run
                 WHERE dag_id = %s AND state = 'running'
                 GROUP BY backfill_id IS NULL
                """,
                (_CUSTOMERS_DAG_ID,),
            )
            counts = dict(cur.fetchall())
        if counts.get(True, 0) > 0 and counts.get(False, 0) > 0:
            observed_concurrent = True
            break
        time.sleep(_POLL_INTERVAL_SECONDS)

    # Sizing: same live-observed per-dagrun pace as test_idempotent_rerun's own comment above
    # (KPO pod-startup cost dominates, not row count) -- 2700s (45 min) for this single-window
    # backfill under this cluster's real CPU contention, with headroom.
    _wait_for_new_backfill_completed(
        airflow_metadata_connection,
        dag_id=_CUSTOMERS_DAG_ID,
        since_backfill_id=since_id,
        timeout=2700,
    )

    assert observed_concurrent, (
        "never observed a customers DagRun with backfill_id IS NOT NULL and a customers DagRun "
        "with backfill_id IS NULL BOTH state='running' at the same sampled instant within 300s "
        "-- D-13's live+backfill concurrency proof requires this overlap to actually occur, not "
        "just be architecturally possible"
    )

    # No corruption -- rewritten (plan 10-07 Task 2, RESEARCH.md Pattern 4): migration 0035
    # (plan 10-01) replaced normalized.customers's UNIQUE(customer_id) constraint with an
    # EXCLUDE USING gist constraint over (customer_id, validity) -- MULTIPLE rows per
    # customer_id are now the expected, correct SCD2 shape (this whole sweep's own Task 1
    # assertions prove customers legitimately carrying 2-3 version rows), so the ORIGINAL
    # "any duplicate customer_id row" check would misclassify every one of those as
    # corruption. The real SCD2 invariant under concurrent writes is TWO-FOLD: (a) at most
    # ONE is_current row per key, and (b) no two version rows for the same key ever have
    # overlapping validity ranges. Both are checked live here -- the exclusion constraint
    # SHOULD make (b) structurally impossible (RESEARCH.md's own "should never actually
    # fire" framing), but this test proves it holds under REAL concurrency, not merely via
    # the DDL's own guarantee.
    with analytics_connection.cursor() as cur:
        cur.execute(
            """
            SELECT customer_id, count(*)
              FROM normalized.customers
             WHERE is_current
             GROUP BY customer_id
            HAVING count(*) > 1
             LIMIT 5
            """
        )
        multiple_current = cur.fetchall()
    assert not multiple_current, (
        f"found customer_id(s) with MORE THAN ONE is_current=true row in "
        f"normalized.customers (genuine SCD2 corruption -- at most one current version per "
        f"key is required): {multiple_current!r}"
    )
    with analytics_connection.cursor() as cur:
        cur.execute(
            """
            SELECT a.customer_id
              FROM normalized.customers a
              JOIN normalized.customers b
                ON a.customer_id = b.customer_id
               AND a.id <> b.id
               AND a.validity && b.validity
             LIMIT 5
            """
        )
        overlapping_validity = cur.fetchall()
    assert not overlapping_validity, (
        f"found customer_id(s) with OVERLAPPING validity ranges in normalized.customers -- "
        f"the excl_customers_business_key_validity exclusion constraint (migration 0035) "
        f"should make this structurally impossible; a live occurrence would be genuine "
        f"corruption under concurrent writes: {overlapping_validity!r}"
    )


