def _dry_run_tick_count(
    kubectl_fn: Callable[..., subprocess.CompletedProcess[str]],
    *,
    dag_id: str,
    from_iso: str,
    to_iso: str,
) -> int:
    """Invoke `airflow backfill create --dry-run` and count the enumerated ticks.

    Pitfall 1's exact failure mode this guards against: an unbounded window enumerating tens or
    hundreds of thousands of DagRuns. Asserts CLI success separately from the tick count so a
    genuine CLI failure (e.g. `DagNonPeriodicScheduleException`) is never miscounted as `0` ticks.
    """
    result = _kubectl_airflow(
        kubectl_fn,
        "backfill", "create",
        "--dag-id", dag_id,
        "--from-date", from_iso,
        "--to-date", to_iso,
        "--dry-run",
    )
    assert result.returncode == 0, (
        f"airflow backfill create --dry-run --dag-id {dag_id} failed "
        f"(exit {result.returncode}):\n{result.stdout}\n{result.stderr}"
    )
    return len(_DRY_RUN_TICK_PATTERN.findall(result.stdout))


def _invoke_backfill_create(  # noqa: PLR0913 -- one keyword per D-11-locked CLI flag + retry knobs
    kubectl_fn: Callable[..., subprocess.CompletedProcess[str]],
    *,
    dag_id: str,
    from_iso: str,
    to_iso: str,
    max_active_runs: int,
    max_attempts: int = 3,
    retry_backoff_seconds: float = 5.0,
) -> subprocess.CompletedProcess[str]:
    """Invoke a REAL `airflow backfill create`, D-11's exact locked CLI shape.

    Retries a bounded number of times on outright CLI failure (this project's own documented,
    recurring live-cluster transients -- scheduler contention, a lost `SELECT ... FOR UPDATE
    SKIP LOCKED` race per `.planning/debug/backfill-does-not-redrive-rejected-row.md`) rather than
    failing the whole test on the first transient blip.
    """
    last: subprocess.CompletedProcess[str] | None = None
    for attempt in range(1, max_attempts + 1):
        last = _kubectl_airflow(
            kubectl_fn,
            "backfill", "create",
            "--dag-id", dag_id,
            "--from-date", from_iso,
            "--to-date", to_iso,
            "--max-active-runs", str(max_active_runs),
            "--reprocess-behavior", "completed",
        )
        if last.returncode == 0:
            return last
        if attempt < max_attempts:
            time.sleep(retry_backoff_seconds)
    assert last is not None, "unreachable: the loop above always assigns `last` at least once"
    assert last.returncode == 0, (
        f"airflow backfill create --dag-id {dag_id} --from-date {from_iso} --to-date {to_iso} "
        f"failed after {max_attempts} attempts (exit {last.returncode}):\n"
        f"{last.stdout}\n{last.stderr}"
    )
    return last


