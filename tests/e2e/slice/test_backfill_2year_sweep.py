def _minute_aligned_utc_now() -> datetime:
    return datetime.now(UTC).replace(second=0, microsecond=0)


def _window(*, offset_minutes: int, span_minutes: int) -> tuple[datetime, datetime]:
    """A `(from_date, to_date)` pair, minute-aligned, `offset_minutes` before `now()`.

    `span_minutes` ticks span `[start, start + span_minutes]` inclusive on both ends (verified
    live: `--from-date 00:00 --to-date 00:05` enumerates 6 ticks, :00 through :05).
    """
    start = _minute_aligned_utc_now() - timedelta(minutes=offset_minutes)
    end = start + timedelta(minutes=span_minutes)
    return start, end


