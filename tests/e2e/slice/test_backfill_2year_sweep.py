def test_full_2year_sweep_customers_and_orders(  # noqa: PLR0915 -- 7 independently-named
    # correctness properties (D-05..D-11), each needing its own setup/query/assert; splitting
    # would scatter one coherent live proof across artificial fixtures for no reader benefit.
    sweep_corpus: _Corpus,
    sweep_state: _SweepState,
    kubectl: Callable[..., subprocess.CompletedProcess[str]],
    analytics_connection: psycopg.Connection[Any],
    airflow_metadata_connection: psycopg.Connection[Any],
) -> None:
    """The 7-assertion live proof (D-05..D-11), see module docstring for the 3 deviations.

    Runs a REAL `airflow backfill create` for `csv_ingest_customers` only (Deviation 1: orders
    cannot be targeted directly -- `DagNonPeriodicScheduleException`), waits for every generated
    file in BOTH datasets to reach a terminal `meta.ingestion_runs` status (orders drains via its
    own Asset-triggered cascade off customers' publish), then asserts all 7 correctness
    properties via direct SQL.
    """
    from_dt, to_dt = _window(offset_minutes=400, span_minutes=2)
    sweep_state.full_sweep_from = from_dt
    sweep_state.full_sweep_to = to_dt

    since_id = _latest_backfill_id(airflow_metadata_connection, dag_id=_CUSTOMERS_DAG_ID)
    _invoke_backfill_create(
        kubectl,
        dag_id=_CUSTOMERS_DAG_ID,
        from_iso=from_dt.isoformat(),
        to_iso=to_dt.isoformat(),
        max_active_runs=sweep_state.max_active_runs,
    )
    # Sizing: at max_active_runs=1 (fully sequential, no concurrent pod-scheduling pressure),
    # 3 sequential customers dag_runs at the observed ~20-25 min/run pace under this cluster's
    # CPU contention could take up to ~75 min total -- 5400s (90 min) budgets that with headroom.
    _wait_for_new_backfill_completed(
        airflow_metadata_connection,
        dag_id=_CUSTOMERS_DAG_ID,
        since_backfill_id=since_id,
        timeout=5400,
    )

    customers_manifest = sweep_corpus.customers_manifest
    orders_manifest = sweep_corpus.orders_manifest

    customers_results = _wait_for_dataset_files_terminal(
        analytics_connection,
        dataset=_CUSTOMERS_DATASET,
        filenames=customers_manifest.filenames,
        timeout=5400,
    )
    for filename, result in customers_results.items():
        assert result["status"] == "SUCCEEDED", (
            f"customers file {filename!r} finished {result['status']!r}, not SUCCEEDED"
        )

    # Deviation 1: orders drains via its OWN Asset-triggered cascade, never a direct backfill
    # CLI call -- poll for the SAME terminal-status guarantee regardless of trigger mechanism.
    # Sizing: at max_active_runs=1, orders' own 13-file drain only starts once customers' full
    # sequential 3-run backfill completes and fires the asset event, ON TOP OF its own
    # observed ~1-2 min/file serialized cadence under CPU contention -- 5400s (90 min) budgets
    # a full 13-file drain at that rate plus generous headroom (err generous rather than
    # re-guessing a tighter number again).
    orders_results = _wait_for_dataset_files_terminal(
        analytics_connection,
        dataset=_ORDERS_DATASET,
        filenames=orders_manifest.filenames,
        timeout=5400,
    )
    for filename, result in orders_results.items():
        assert result["status"] == "SUCCEEDED", (
            f"orders file {filename!r} finished {result['status']!r}, not SUCCEEDED"
        )

    expected_row_count = (_NUM_DAYS - 1) * _ROWS_PER_DAY  # gap day excluded, no dedup collisions

    # --- (1) silver.orders/normalized.orders non-empty, consistent with the corpus minus the gap
    #     day (D-08: closes the silver.orders 0-rows gap). ---
    # `normalized.orders`/`silver.orders` are shared, cluster-wide tables -- other live e2e
    # suites (e.g. test_referential_orphan.py, its own disjoint order_id range per
    # dated_series.py's module docstring) leave their own rows behind too, so an unscoped
    # `count(*)` over-counts (live-discovered this session: got 656 against an expected 650,
    # traced to exactly 6 rows outside this corpus' own order_id range). Scope both counts to
    # THIS corpus' own order_id space (`_ORDER_ID_BASE` .. `+ _NUM_DAYS * _ID_DAY_MULTIPLIER`,
    # generously wide -- `_ROWS_PER_DAY` rows/day never approaches the multiplier) so the
    # assertion reflects only what this run itself produced.
    order_id_upper_bound = _ORDER_ID_BASE + _NUM_DAYS * _ID_DAY_MULTIPLIER
    silver_orders_count = _scoped_row_count(
        analytics_connection, "silver.orders", "order_id", _ORDER_ID_BASE, order_id_upper_bound
    )
    normalized_orders_count = _scoped_row_count(
        analytics_connection,
        "normalized.orders",
        "order_id",
        _ORDER_ID_BASE,
        order_id_upper_bound,
    )
    assert silver_orders_count > 0, "silver.orders is empty -- D-08's 0-rows gap did not close"
    assert normalized_orders_count > 0, (
        "normalized.orders is empty -- D-08's 0-rows gap did not close"
    )
    assert normalized_orders_count == expected_row_count, (
        f"expected normalized.orders row count == {expected_row_count} "
        f"(({_NUM_DAYS} - 1 gap) * {_ROWS_PER_DAY} rows/day; this corpus' orders.customer_id "
        f"pool is drawn from customers' own day-0 range, so every row resolves referentially "
        f"clean, no quarantine expected), got {normalized_orders_count}"
    )

    # --- (2, adapted -- module docstring Deviation 3): the gap day is genuinely absent
    #     everywhere, every OTHER day was processed, and meta.processing_gaps correctly has
    #     ZERO rows for this whole-bucket-populated corpus (its real, live-confirmed semantics
    #     is "the whole listing was empty", not "one day is missing among many present"). ---
    gap_day = _START_DATE + timedelta(days=_GAP_DAY_INDEX)
    gap_filename = f"customers_{gap_day.strftime('%Y%m%d')}.csv"
    assert gap_filename not in customers_results, (
        f"the gap day's file {gap_filename!r} unexpectedly has a meta.ingestion_runs row -- it "
        f"was never uploaded and must never be discovered"
    )
    assert len(customers_results) == len(customers_manifest.filenames) == _NUM_DAYS - 1, (
        "expected every non-gap day's file to be discovered and reach a terminal status -- the "
        "gap must not stop the rest of the window"
    )
    gap_rows = _table_row_count(analytics_connection, "meta.processing_gaps")
    assert gap_rows == 0, (
        f"meta.processing_gaps has {gap_rows} row(s), expected 0: this corpus keeps "
        f"{len(customers_manifest.filenames)} real files permanently in the bucket, so "
        f"list_matched_keys (bucket-wide, date-agnostic) is never empty for any tick -- "
        f"record_processing_gap_if_empty's real, live-confirmed semantics only fire on a "
        f"WHOLE-LISTING-EMPTY tick, not a single missing day among many present ones (module "
        f"docstring Deviation 3) -- 0 is the CORRECT value here, not a bug"
    )

    # --- (3) pre-schema-change files resolve under their OWN historical schema version,
    #     differing from post-schema-change runs' version (D-07). ---
    pre_change_day = _START_DATE  # day_index=0, always < schema_change_day_index
    pre_change_filename = f"customers_{pre_change_day.strftime('%Y%m%d')}.csv"
    post_change_day = _START_DATE + timedelta(days=_SCHEMA_CHANGE_DAY_INDEX)
    post_change_filename = f"customers_{post_change_day.strftime('%Y%m%d')}.csv"
    pre_schema_version_id = customers_results[pre_change_filename]["schema_version_id"]
    post_schema_version_id = customers_results[post_change_filename]["schema_version_id"]
    assert pre_schema_version_id is not None, f"{pre_change_filename!r} has no schema_version_id"
    assert post_schema_version_id is not None, f"{post_change_filename!r} has no schema_version_id"
    assert pre_schema_version_id != post_schema_version_id, (
        f"pre-schema-change file {pre_change_filename!r} (schema_version_id="
        f"{pre_schema_version_id!r}) and post-schema-change file {post_change_filename!r} "
        f"(schema_version_id={post_schema_version_id!r}) resolved under the SAME schema "
        f"version -- D-07's historical-schema-resolution proof requires them to differ"
    )

    # --- (4) the late/out-of-order record lands correctly ordered by BUSINESS timestamp, not
    #     arrival order (D-05); every row's business key is globally unique in this corpus (no
    #     dedup collision is even possible), so the proof is that the late row's OWN event_ts in
    #     normalized.customers matches its BACKDATED value verbatim -- never silently corrected
    #     forward to its file's nominal day. ---
    late_day = _START_DATE + timedelta(days=_LATE_EVENT_DAY_INDEX)
    late_filename = f"customers_{late_day.strftime('%Y%m%d')}.csv"
    late_run_id = customers_results[late_filename]["run_id"]
    with analytics_connection.cursor() as cur:
        cur.execute(
            "SELECT customer_id FROM silver.customers WHERE _run_id = %s "
            "ORDER BY event_ts ASC LIMIT 1",
            (late_run_id,),
        )
        late_silver_row = cur.fetchone()
    assert late_silver_row is not None, f"silver.customers has no rows for _run_id={late_run_id!r}"
    late_customer_id = int(late_silver_row[0])
    expected_late_event_ts = datetime(
        late_day.year, late_day.month, late_day.day, 8, 15, 0, tzinfo=UTC
    ) - timedelta(days=_LATE_EVENT_OFFSET_DAYS)
    with analytics_connection.cursor() as cur:
        cur.execute(
            "SELECT event_ts FROM normalized.customers WHERE customer_id = %s",
            (late_customer_id,),
        )
        late_gold_row = cur.fetchone()
    assert late_gold_row is not None, f"late customer_id={late_customer_id!r} never published"
    assert late_gold_row[0] == expected_late_event_ts, (
        f"expected the late row's (customer_id={late_customer_id!r}) own event_ts to be its "
        f"backdated value {expected_late_event_ts!r} (never silently corrected to the file's "
        f"nominal day {late_day!r}), got {late_gold_row[0]!r}"
    )

    # --- (5) meta.watermarks.cursor_value equals the TRUE max event_ts/order_date across the
    #     whole corpus -- never the late event's earlier value, never simply "today" (INCR-01/
    #     02's live proof). ---
    last_day = _START_DATE + timedelta(days=_NUM_DAYS - 1)
    expected_customers_watermark = datetime(
        last_day.year, last_day.month, last_day.day, 8, 15, 0, tzinfo=UTC
    )
    customers_watermark = _watermark_cursor_value(analytics_connection, dataset=_CUSTOMERS_DATASET)
    assert customers_watermark == expected_customers_watermark, (
        f"expected meta.watermarks.cursor_value for customers == "
        f"{expected_customers_watermark!r} (the corpus' own true last day -- never the late "
        f"event's backdated {expected_late_event_ts!r} value, never simply 'today'), got "
        f"{customers_watermark!r}"
    )
    expected_orders_watermark = datetime(
        last_day.year, last_day.month, last_day.day, tzinfo=UTC
    )
    orders_watermark = _watermark_cursor_value(analytics_connection, dataset=_ORDERS_DATASET)
    assert orders_watermark == expected_orders_watermark, (
        f"expected meta.watermarks.cursor_value for orders == {expected_orders_watermark!r}, "
        f"got {orders_watermark!r}"
    )

    # --- (6) meta.reconciliation_results has rows for all 3 hops for every processed file, with
    #     D-22's own accounting formula holding exactly. ---
    for dataset, manifest in (
        (_CUSTOMERS_DATASET, customers_manifest),
        (_ORDERS_DATASET, orders_manifest),
    ):
        for hop in ("raw_bronze", "bronze_silver", "silver_gold"):
            rows = _reconciliation_rows(analytics_connection, dataset=dataset, hop=hop)
            assert rows, (
                f"meta.reconciliation_results has zero rows for dataset={dataset!r} hop={hop!r}"
            )
            observed_file_ids = {row["file_id"] for row in rows}
            source_results = customers_results if dataset == _CUSTOMERS_DATASET else orders_results
            expected_file_ids = {source_results[f]["file_id"] for f in manifest.filenames}
            assert expected_file_ids <= observed_file_ids, (
                f"dataset={dataset!r} hop={hop!r}: expected reconciliation rows for every "
                f"processed file_id, missing {expected_file_ids - observed_file_ids!r}"
            )
            for row in rows:
                if row["file_id"] not in expected_file_ids:
                    continue  # a row from an earlier plan's own live-proof run, not this sweep's
                assert row["discrepancy"] == row["input_count"] - (
                    row["output_count"] + row["rejected_count"] + row["dedup_count"]
                ), (
                    f"D-22's own accounting formula does not hold for dataset={dataset!r} "
                    f"hop={hop!r} file_id={row['file_id']!r}: {row!r}"
                )

    # --- (7) a normal live-scheduled DagRun (backfill_id IS NULL) ALSO succeeds through the
    #     identical task graph, no special-casing (D-11). Orders is Asset-triggered
    #     (Deviation 1): EVERY orders DagRun this sweep produced is inherently backfill_id IS
    #     NULL, which is itself the proof -- orders never even has a "backfill mode" to special-
    #     case, because it always runs through the ONE structure it has. ---
    with airflow_metadata_connection.cursor() as cur:
        cur.execute(
            "SELECT count(*) FROM dag_run "
            "WHERE dag_id = %s AND backfill_id IS NULL AND state = 'success'",
            (_ORDERS_DAG_ID,),
        )
        orders_live_success_row = cur.fetchone()
    assert orders_live_success_row is not None
    orders_live_success_count = orders_live_success_row[0]
    assert orders_live_success_count > 0, (
        "expected at least one csv_ingest_orders DagRun with backfill_id IS NULL to reach "
        "'success' -- orders is Asset-triggered (module docstring Deviation 1), so this "
        "confirms it processed this sweep's files through the SAME task graph a live trigger "
        "would use, with no bypass or special-casing by temporal mode"
    )


