def _failed_scheduling_event_snapshot(
    kubectl_json_fn: Callable[..., Any],
) -> dict[str, int]:
    """`{event_uid: count}` for every `FailedScheduling` event currently in the `etl` namespace.

    Kubernetes coalesces repeated identical events (bumping `count`/`lastTimestamp` on the SAME
    object) rather than creating new ones -- comparing `count` per UID before/after a window
    catches both a brand-new event AND a pre-existing one recurring, without over-counting stale
    history the pilot's own run never caused.
    """
    result = kubectl_json_fn(
        "-n", _ETL_NAMESPACE, "get", "events",
        "--field-selector=reason=FailedScheduling", "-o", "json",
    )
    return {item["metadata"]["uid"]: item.get("count", 1) for item in result.get("items", [])}


